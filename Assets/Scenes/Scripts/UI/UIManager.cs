using System.Collections;
using UnityEngine;
using UnityEngine.UI;
using TMPro;

/// <summary>
/// Central UI controller (singleton). Other scripts call UIManager.Instance
/// to update the on-screen counter, show subtitles and trigger visual feedback.
/// </summary>
public class UIManager : MonoBehaviour
{
    /// <summary>
    /// Global access point to the single UIManager in the scene.
    /// </summary>
    public static UIManager Instance { get; private set; }

    [Header("UI Text References")]
    [Tooltip("TextMeshPro text showing how many calm lights the player has collected.")]
    [SerializeField] private TextMeshProUGUI calmLightsText;

    [Tooltip("TextMeshPro text used for subtitles, so audio information is also visual (WCAG 1.2.2).")]
    [SerializeField] private TextMeshProUGUI subtitleText;

    [Header("Visual Feedback")]
    [Tooltip("Full-screen UI Image used for the soft flash effect.")]
    [SerializeField] private Image flashPanel;

    [Tooltip("Maximum opacity of the flash (kept low for comfort).")]
    [Range(0f, 1f)]
    [SerializeField] private float flashIntensity = 0.35f;

    [Tooltip("Seconds the flash takes to fade out (slow fade, WCAG 2.3.1).")]
    [SerializeField] private float flashFadeDuration = 0.8f;

    private Coroutine subtitleRoutine;
    private Coroutine flashRoutine;

    /// <summary>
    /// Enforces the singleton pattern: a duplicate UIManager is destroyed.
    /// </summary>
    private void Awake()
    {
        if (Instance != null && Instance != this)
        {
            Destroy(gameObject);
            return;
        }

        Instance = this;
    }

    /// <summary>
    /// Updates the calm lights counter showing only the collected amount.
    /// </summary>
    /// <param name="count">Number of calm lights collected.</param>
    public void UpdateCalmLights(int count)
    {
        if (calmLightsText != null)
        {
            calmLightsText.text = "Calm Lights: " + count;
        }
    }

    /// <summary>
    /// Updates the calm lights counter showing collected and total amounts.
    /// </summary>
    /// <param name="count">Number of calm lights collected.</param>
    /// <param name="total">Total number of calm lights in the level.</param>
    public void UpdateCalmLights(int count, int total)
    {
        if (calmLightsText != null)
        {
            calmLightsText.text = "Calm Lights: " + count + " / " + total;
        }
    }

    /// <summary>
    /// Shows a subtitle message that stays on screen until replaced.
    /// </summary>
    /// <param name="text">Message to display.</param>
    public void DisplaySubtitle(string text)
    {
        if (subtitleText != null)
        {
            subtitleText.text = text;
        }
    }

    // Generated by AI (Claude):
    // ShowSubtitle, HideSubtitleAfter, TriggerVisualFeedback and FlashRoutine.

    /// <summary>
    /// Shows a subtitle and hides it automatically after the given time.
    /// </summary>
    /// <param name="message">Message to display.</param>
    /// <param name="duration">Seconds the message stays visible.</param>
    public void ShowSubtitle(string message, float duration = 3f)
    {
        if (subtitleText == null)
            return;

        // Stop the previous timer so a new message is not hidden too early.
        if (subtitleRoutine != null)
        {
            StopCoroutine(subtitleRoutine);
        }

        subtitleText.text = message;
        subtitleRoutine = StartCoroutine(HideSubtitleAfter(duration));
    }

    /// <summary>
    /// Waits for the given time and then clears the subtitle text.
    /// </summary>
    private IEnumerator HideSubtitleAfter(float duration)
    {
        yield return new WaitForSeconds(duration);

        if (subtitleText != null)
        {
            subtitleText.text = "";
        }

        subtitleRoutine = null;
    }

    /// <summary>
    /// Plays a single soft flash as visual feedback
    /// for important events, such as collecting a calm light.
    /// </summary>
    public void TriggerVisualFeedback()
    {
        if (flashPanel == null)
            return;

        if (flashRoutine != null)
        {
            StopCoroutine(flashRoutine);
        }

        flashRoutine = StartCoroutine(FlashRoutine());
    }

    /// <summary>
    /// Fades the flash panel from its peak opacity down to transparent.
    /// </summary>
    private IEnumerator FlashRoutine()
    {
        Color color = flashPanel.color;
        float elapsed = 0f;

        color.a = flashIntensity;
        flashPanel.color = color;

        while (elapsed < flashFadeDuration)
        {
            elapsed += Time.deltaTime;

            color.a = Mathf.Lerp(
                flashIntensity,
                0f,
                elapsed / flashFadeDuration
            );

            flashPanel.color = color;

            yield return null;
        }

        color.a = 0f;
        flashPanel.color = color;

        flashRoutine = null;
    }

    // Test helpers:
    // Right-click the UIManager component title in the Inspector while in Play Mode.

    [ContextMenu("Test Subtitle")]
    private void TestSubtitle()
    {
        ShowSubtitle("Test subtitle", 2f);
    }

    [ContextMenu("Test Flash")]
    private void TestFlash()
    {
        TriggerVisualFeedback();
    }
}